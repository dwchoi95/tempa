"""Generate mech/SurfSemTests.lean (run with PYTHONHASHSEED=0): `#guard` runs of the Lean Surf interpreter on the programs in
cases/, one per construct family, against the output (and uncaught exception's class) that
python3 gives them. python3 -I gen_tests.py"""
import contextlib, io, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "lean_cls"))
from export_surf import export   # noqa: E402

STDIN = "7\n1 2 3\nrest line\n"


def cpython(src):
    buf = io.StringIO()
    real = sys.stdin
    sys.stdin = io.StringIO(STDIN)
    try:
        with contextlib.redirect_stdout(buf):
            exec(compile(src, "<case>", "exec"), {"__name__": "__main__"})
    except SystemExit:
        pass
    except BaseException as e:
        buf.write("!" + type(e).__name__)
    finally:
        sys.stdin = real
    return buf.getvalue()


def lean_str(s):
    out = []
    for c in s:
        if c == "\\": out.append("\\\\")
        elif c == '"': out.append('\\"')
        elif c == "\n": out.append("\\n")
        elif c == "\t": out.append("\\t")
        elif ord(c) < 0x20 or ord(c) > 0x7e: out.append("\\u{%x}" % ord(c))
        else: out.append(c)
    return '"' + "".join(out) + '"'


lines = ["/-", "Runs of the Surf semantics with the reference interpretation (`Surf.Run.runSrc`), one",
         "program per construct family (`results/checks/lean_sem/cases/`), each checked against",
         "the output and uncaught exception's class that python3 (CPython 3.13) gives it; generated by",
         "`results/checks/lean_sem/gen_tests.py`.", "-/", "import Surf.Run", "", "open Surf.Run", "",
         f"def stdin : String := {lean_str(STDIN)}", ""]
for f in sorted((HERE / "cases").glob("*.py")):
    src = f.read_text()
    exp = cpython(src)
    sx = export(src)[0]
    lines.append(f"-- {f.name}")
    lines.append(f"#guard runSrc {lean_str(sx)} stdin ==\n  {lean_str(exp)}")
    lines.append("")
(HERE.parents[2] / "mech" / "SurfSemTests.lean").write_text("\n".join(lines))
print(len(list((HERE / "cases").glob("*.py"))), "cases")
